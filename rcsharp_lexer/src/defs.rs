use rcsharp_syntax::{Span, Symbol};

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum TokenKind {
    LParen,
    RParen,
    LBrace,
    RBrace,
    LSquareBrace,
    RSquareBrace,
    Colon,
    DoubleColon,
    SemiColon,
    Comma,
    Dot,
    RangeDots,
    RangeDotsInclusive,

    FatArrow,
    Hash,

    Equal,
    Plus,
    Minus,
    Multiply,
    Divide,
    Modulo,
    LogicNot,
    LogicEqual,
    LogicNotEqual,
    LogicOr,
    LogicAnd,
    LogicGreater,
    LogicGreaterEqual,
    LogicLess,
    LogicLessEqual,
    BinaryNot,
    BinaryOr,
    BinaryAnd,
    BinaryXor,
    BinaryShiftL,
    BinaryShiftR,

    KeywordPub,
    KeywordInline,
    KeywordConst,
    KeywordConstExpr,
    KeywordExtern,
    KeywordMatch,
    KeywordFunction,
    KeywordLet,
    KeywordStatic,
    KeywordAs,
    KeywordIf,
    KeywordElse,
    KeywordTrait,
    KeywordImpl,
    KeywordStruct,
    KeywordEnum,
    KeywordLoop,
    KeywordFor,
    KeywordDo,
    KeywordIn,
    KeywordWhile,
    KeywordBreak,
    KeywordContinue,
    KeywordReturn,
    KeywordThis,
    KeywordOperator,
    KeywordNamespace,
    KeywordTrue,
    KeywordFalse,
    KeywordNull,

    Name(Symbol),
    Integer(Symbol),
    Decimal(Symbol),
    String(Symbol),
    Char(char),
    EOF,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}

pub const KEYWORDS_TO_TOKENS: phf::Map<&'static str, TokenKind> = phf::phf_map!(
    "pub"       => TokenKind::KeywordPub,
    "inline"    => TokenKind::KeywordInline,
    "const"     => TokenKind::KeywordConst,
    "constexpr" => TokenKind::KeywordConstExpr,
    "extern"    => TokenKind::KeywordExtern,
    "match"     => TokenKind::KeywordMatch,
    "fn"        => TokenKind::KeywordFunction,
    "let"       => TokenKind::KeywordLet,
    "static"    => TokenKind::KeywordStatic,
    "as"        => TokenKind::KeywordAs,
    "if"        => TokenKind::KeywordIf,
    "else"      => TokenKind::KeywordElse,
    "struct"    => TokenKind::KeywordStruct,
    "enum"      => TokenKind::KeywordEnum,
    "loop"      => TokenKind::KeywordLoop,
    "for"      => TokenKind::KeywordFor,
    "in"      => TokenKind::KeywordIn,
    "do"      => TokenKind::KeywordDo,
    "while"      => TokenKind::KeywordWhile,
    "break"     => TokenKind::KeywordBreak,
    "continue"  => TokenKind::KeywordContinue,
    "return"    => TokenKind::KeywordReturn,
    "this"      => TokenKind::KeywordThis,
    "operator"  => TokenKind::KeywordOperator,
    "namespace" => TokenKind::KeywordNamespace,
    "trait" => TokenKind::KeywordTrait,
    "impl" => TokenKind::KeywordImpl,
    "true"      => TokenKind::KeywordTrue,
    "false"     => TokenKind::KeywordFalse,
    "null"      => TokenKind::KeywordNull,
);
pub const SINGLE_CHAR_TO_TOKEN: phf::Map<char, TokenKind> = phf::phf_map!(
    '~' => TokenKind::BinaryNot,
    '#' => TokenKind::Hash,
    '{' => TokenKind::LBrace, '}' => TokenKind::RBrace,
    '[' => TokenKind::LSquareBrace, ']' => TokenKind::RSquareBrace,
    '(' => TokenKind::LParen, ')' => TokenKind::RParen,
    ';' => TokenKind::SemiColon, ',' => TokenKind::Comma,
    '+' => TokenKind::Plus, '-' => TokenKind::Minus,
    '*' => TokenKind::Multiply, '/' => TokenKind::Divide,
    '%' => TokenKind::Modulo, '^' => TokenKind::BinaryXor,
    ':' => TokenKind::Colon, '<' => TokenKind::LogicLess,
    '>' => TokenKind::LogicGreater, '=' => TokenKind::Equal,
    '!' => TokenKind::LogicNot, '|' => TokenKind::BinaryOr,
    '&' => TokenKind::BinaryAnd, '.' => TokenKind::Dot,
);
pub const DOUBLE_CHAR_TO_TOKEN: phf::Map<(char, char), TokenKind> = phf::phf_map!(
    (':', ':') => TokenKind::DoubleColon,
    ('<', '<') => TokenKind::BinaryShiftL,
    ('<', '=') => TokenKind::LogicLessEqual,
    ('>', '>') => TokenKind::BinaryShiftR,
    ('>', '=') => TokenKind::LogicGreaterEqual,
    ('=', '>') => TokenKind::FatArrow,
    ('=', '=') => TokenKind::LogicEqual,
    ('!', '=') => TokenKind::LogicNotEqual,
    ('|', '|') => TokenKind::LogicOr,
    ('&', '&') => TokenKind::LogicAnd,
    ('.', '.') => TokenKind::RangeDots,
);
pub const TRIPLE_CHAR_TO_TOKEN: phf::Map<(char, char, char), TokenKind> = phf::phf_map!(
    ('.', '.', '=') => TokenKind::RangeDotsInclusive,
);
pub fn get_keyword(ident: &str) -> Option<TokenKind> {
    KEYWORDS_TO_TOKENS.get(ident).cloned()
}
